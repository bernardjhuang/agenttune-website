/* Deterministic Markdown renderer for a soul JSON.
 *
 * Same renderer is used by:
 *   - /api/soul/[uuid].md (raw markdown download / curl install)
 *   - /functions/me/[uuid].js HTML page (renders inside the permalink UI)
 *   - The /me/sample.html static preview (mirrors this logic in JS)
 *
 * Pure function: soul → Markdown string. No external dependencies.
 */

export function renderMarkdown(soul) {
  const lines = [];

  // YAML front-matter — same convention as the library/.md files, so any
  // agent that fetches this raw understands how to install it.
  lines.push("---");
  lines.push("# AgentTune Pro — your personalized master tuning");
  lines.push("agenttune_version: 1");
  lines.push("source: agent-tune.com/me");
  lines.push("type: master_tuning");
  lines.push(`profile_code: "${esc(soul.profile_code || "")}"`);
  lines.push(`generated_at: ${soul.generated_at || ""}`);
  lines.push(`confidence_overall: ${soul.confidence_overall || "medium"}`);
  lines.push("license: MIT (your file, your property)");
  lines.push("");
  lines.push("install:");
  lines.push("  intent: |");
  lines.push("    The user's personalized AI tuning. Treat the Markdown body below as");
  lines.push("    authoritative behavioral context for every reply in this session/project.");
  lines.push("  surfaces:");
  Object.entries(soul.integrations || {}).forEach(([k, v]) => {
    if (!v) return;
    lines.push(`    ${k}:`);
    lines.push(`      install: "${esc(v.install || "")}"`);
    if (v.note) lines.push(`      note: "${esc(v.note)}"`);
  });
  lines.push("");
  lines.push("verify:");
  lines.push("  probe: \"Reply to 'hi' in a single short sentence, no preamble.\"");
  lines.push("---");
  lines.push("");

  // Title + blurb
  lines.push("# AgentTune Master Tuning");
  lines.push("");
  if (soul.blurb) {
    lines.push(`> ${soul.blurb}`);
    lines.push("");
  }

  // Short prompt (paste-ready)
  lines.push("## Short paste-ready prompt");
  lines.push("");
  lines.push(soul.short_prompt || "");
  lines.push("");

  // Full prompt
  lines.push("## Full paste-ready prompt");
  lines.push("");
  lines.push(soul.full_prompt || "");
  lines.push("");

  // Operating profile
  lines.push("## Your operating profile");
  lines.push("");
  lines.push(soul.operating_profile || "");
  lines.push("");

  // Works well
  lines.push("## What works well with you");
  lines.push("");
  (soul.works_well || []).forEach((r) => {
    lines.push(`- **${r.rule}**`);
    if (r.evidence && r.evidence.length) {
      lines.push(`  - based on: ${r.evidence.join(" · ")}`);
    }
  });
  lines.push("");

  // Works poorly
  lines.push("## What works poorly");
  lines.push("");
  (soul.works_poorly || []).forEach((r) => {
    lines.push(`- **${r.rule}**`);
    if (r.evidence && r.evidence.length) {
      lines.push(`  - based on: ${r.evidence.join(" · ")}`);
    }
  });
  lines.push("");

  // Challenge protocol
  if (soul.challenge_protocol) {
    lines.push("## How to disagree with me");
    lines.push("");
    lines.push(soul.challenge_protocol);
    lines.push("");
  }

  // Stuck protocol
  if (soul.stuck_protocol) {
    lines.push("## How to help when I'm stuck");
    lines.push("");
    lines.push(soul.stuck_protocol);
    lines.push("");
  }

  // Conflicts
  if (soul.conflicts && soul.conflicts.length) {
    lines.push("## Where the systems disagree (and which to trust)");
    lines.push("");
    soul.conflicts.forEach((c) => {
      const between = (c.between || []).join(" vs ");
      lines.push(`- **${between}**`);
      lines.push(`  - ${c.operational_rule || ""}`);
    });
    lines.push("");
  }

  // Integration variants
  if (soul.integrations) {
    lines.push("## Integration guide");
    lines.push("");
    Object.entries(soul.integrations).forEach(([k, v]) => {
      if (!v) return;
      lines.push(`### ${k.replace(/_/g, " ")}`);
      lines.push(`- **Install:** ${v.install || ""}`);
      if (v.note) lines.push(`- ${v.note}`);
      lines.push("");
    });
  }

  // Evidence
  if (soul.evidence_table && soul.evidence_table.length) {
    lines.push("## Why this file says what it says");
    lines.push("");
    lines.push("| Signal | Interpretation | Confidence |");
    lines.push("| --- | --- | --- |");
    soul.evidence_table.forEach((e) => {
      lines.push(`| ${e.signal || ""} | ${e.interpretation || ""} | ${e.confidence || ""} |`);
    });
    lines.push("");
  }

  // Limits
  if (soul.limits && soul.limits.length) {
    lines.push("## Limits — don't overread this");
    lines.push("");
    soul.limits.forEach((l) => lines.push(`- ${l}`));
    lines.push("");
  }

  // Footer
  lines.push("---");
  lines.push("");
  lines.push(`*Generated by AgentTune Pro · ${soul.generated_at || ""} · profile ${soul.profile_code || ""} · v${soul.version || "1.0"}*`);
  lines.push("");

  return lines.join("\n");
}

function esc(s) {
  return String(s).replace(/"/g, '\\"');
}
